import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { fileURLToPath } from 'node:url';
import { performance } from 'node:perf_hooks';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const external = [
	'obsidian',
	'electron',
	'@codemirror/autocomplete',
	'@codemirror/collab',
	'@codemirror/commands',
	'@codemirror/language',
	'@codemirror/lint',
	'@codemirror/search',
	'@codemirror/state',
	'@codemirror/view',
	'@lezer/common',
	'@lezer/highlight',
	'@lezer/lr',
	...builtinModules,
];

function createContext(prod) {
	return esbuild.context({
		banner: {
			js: banner,
		},
		entryPoints: ['src/obsidian/main.ts'],
		bundle: true,
		external,
		format: 'cjs',
		target: 'es2021',
		logLevel: prod ? 'warning' : 'info',
		sourcemap: prod ? false : 'inline',
		treeShaking: true,
		outfile: 'main.js',
		minify: prod,
	});
}

// Production build used by package_scripts/build.mjs; returns timing and warning count.
export async function buildProduction() {
	const context = await createContext(true);
	try {
		const start = performance.now();
		const result = await context.rebuild();
		return {
			durationMs: performance.now() - start,
			warnings: result.warnings.length,
		};
	} finally {
		await context.dispose();
	}
}

const isDirectRun = process.argv[1] === fileURLToPath(import.meta.url);
if (isDirectRun) {
	const prod = process.argv[2] === 'production';
	const context = await createContext(prod);
	if (prod) {
		await context.rebuild();
		process.exit(0);
	} else {
		await context.watch();
	}
}
